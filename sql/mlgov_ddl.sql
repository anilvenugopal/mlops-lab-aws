COMMENT ON COLUMN mlgov.actor.is_active IS
'Whether this principal may currently act. Deactivating fails closed without deleting the attribution target — past rows still resolve correctly.';


-- ========================================================================
-- External references — one row per (owning table, external system)
-- ========================================================================

CREATE TABLE mlgov.model_version_external_reference (
    model_version_id      uuid NOT NULL,
    external_system_code  text NOT NULL,
    external_key          text NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_model_version_external_reference PRIMARY KEY (model_version_id, external_system_code),
    -- fk_model_version_external_reference_version is added by ALTER TABLE
    -- once model_version is created, later in this file.
    CONSTRAINT fk_model_version_external_reference_system FOREIGN KEY (external_system_code)
        REFERENCES mlgov.external_system (code) ON DELETE RESTRICT
);
COMMENT ON TABLE mlgov.model_version_external_reference IS
'A typed pointer from a model_version into a system mlgov does not own — a SageMaker model package ARN, a Feast Feature Service name, an MLflow model version string. external_key is stored verbatim in that system''s own key format, never translated into a uuid. A model_version has at most one row per external_system_code (the primary key), and zero, one, or several rows total across different systems; adding support for a new external system is a new external_system row plus new model_version_external_reference rows, never a schema change here. mlgov does not treat these as the source of truth for anything beyond the pointer itself — it does not sync or cache SageMaker/Feast/MLflow facts. Its foreign key to model_version is added later in this file, once that table exists.';
COMMENT ON COLUMN mlgov.model_version_external_reference.external_key IS
'The native key in the external system: an ARN, an endpoint name, a feature service name, an MLflow "<registered_model_name>/<version_number>" string — verbatim, no reformatting.';


