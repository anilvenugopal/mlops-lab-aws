-- mlgov schema — governance metamodel for the piq-mlplatform lab.
--
-- Applies to schema `mlgov` on the same PostgreSQL instance as the Feast
-- registry (schema `feast`), per SETUP.md section 2. No foreign keys cross
-- the schema boundary — Feast owns its own tables via `feast apply`; this
-- file is the only source of `mlgov` DDL, applied identically whether the
-- instance is the local sandbox container or AWS RDS. See
-- mlops-sandbox/README.md for how the local container applies this file.
--
-- Design lineage: a hand-picked, small subset of the table shapes and
-- naming conventions from the Verity governance platform
-- (github.com/anilvenugopal/verity, specs/schema/), adapted to this lab's
-- scale (two trained ML models, not a fleet of agents). Borrowed
-- deliberately: the append-only lifecycle/champion pattern, the model-card
-- review-state pattern, the approval-request/signoff gating pattern, and
-- the actor attribution model. Not borrowed: Verity's Controls & Evidence
-- (compliance/regulatory) axis, Intake, Asset Registry composition, and
-- Harness Runtime — out of scope for this lab.
--
-- Naming: snake_case throughout; every table has a surrogate primary key
-- named <table>_id, generated by uuidv7() (time-ordered, so inserts stay
-- index-local — requires PostgreSQL 18+, see mlops-sandbox/compose.yml);
-- PK constraints are named pk_<table>, FK constraints fk_<table>_<ref>.
-- Append-only tables are named <entity>_event or similarly, with a paired
-- `<entity>_current` view resolving current state from the latest row —
-- there is no mutable "current status" column anywhere in this schema.
--
-- Key compatibility: this schema does not duplicate data owned by SageMaker,
-- Feast, or MLflow. A model's SageMaker model package, the endpoint that
-- served a prediction, and similar external facts are held as typed
-- pointers (external_system_code + external_key, stored verbatim as text)
-- directly on model_version_external_reference / prediction_event_external_
-- reference, never copied in as denormalized columns on model_version or
-- prediction_event themselves. The one further exception is
-- prediction_event.entity_id: the Feast entity key (e.g. claim_id) is a
-- direct text column on prediction_event itself, because it is core to
-- every row of the platform's highest-volume table, not optional metadata.

CREATE SCHEMA IF NOT EXISTS mlgov;

