CREATE TABLE mlgov.hitl_override (
    hitl_override_id    uuid        NOT NULL DEFAULT uuidv7(),
    prediction_event_id  uuid        NOT NULL,
    field_path            text        NOT NULL,
    original_value         jsonb,
    override_value         jsonb       NOT NULL,
    reason                  text        NOT NULL,
    reason_code_family      text,
    actor_id                uuid        NOT NULL,
    acting_role_code        text        NOT NULL,
    created_at               timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_hitl_override PRIMARY KEY (hitl_override_id),
    CONSTRAINT fk_hitl_override_prediction FOREIGN KEY (prediction_event_id)
        REFERENCES mlgov.prediction_event (prediction_event_id) ON DELETE RESTRICT,
    CONSTRAINT fk_hitl_override_actor FOREIGN KEY (actor_id)
        REFERENCES mlgov.actor (actor_id) ON DELETE RESTRICT,
    CONSTRAINT fk_hitl_override_role FOREIGN KEY (acting_role_code)
        REFERENCES mlgov.role (code) ON DELETE RESTRICT
);
CREATE INDEX ix_hitl_override_prediction ON mlgov.hitl_override (prediction_event_id);
COMMENT ON TABLE mlgov.hitl_override IS
'An additive, per-field human correction to a prediction_event: neither input nor ground truth (see data_generator/DATA_DICTIONARY.md, "The three roles a table plays"). The reviewer keeps the model''s original value, supplies an override, and records why, unverified at the moment it is recorded. Overrides never mutate the prediction; they are appended as their own audited facts. This is the real governance-side home for what the data generator''s synthetic adjuster_decision table stands in for — once a model is actually live, real adjuster overrides land here, against real prediction_event rows, rather than as pre-generated synthetic history.';
COMMENT ON COLUMN mlgov.hitl_override.field_path IS
'Which field of prediction_event.decision was overridden, so corrections are precise and additive rather than wholesale — e.g. "is_total_loss".';
COMMENT ON COLUMN mlgov.hitl_override.original_value IS
'The model''s value before the override, retained for audit and disagreement analysis.';
COMMENT ON COLUMN mlgov.hitl_override.reason_code_family IS
'Coarse attribution of the override — feature | model | process — matching the taxonomy in data_generator/config.yaml''s adjuster.reason_mix, so synthetic and real override data stay comparable. Nullable; free-text reason is always required, this is a classification on top of it.';
