CREATE TABLE mlgov.model (
    model_id    uuid        NOT NULL DEFAULT uuidv7(),
    name        text        NOT NULL,
    description text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_model PRIMARY KEY (model_id),
    CONSTRAINT uq_model_name UNIQUE (name)
);
COMMENT ON TABLE mlgov.model IS
'Identity only — no version-specific config, no SageMaker/Feast pointers, no kind-specific fields. Today every row here is a trained ML model (total-loss-fnol, claim-severity); this table is deliberately kind-agnostic so a future LLM-backed or JEV model registers here too without a rename. Everything that varies by version lives on model_version; everything that varies by kind would live in a kind-specific detail table keyed off model_version, added when a second kind actually exists.';
COMMENT ON COLUMN mlgov.model.name IS
'Stable name, e.g. total-loss-fnol or claim-severity. Unique.';


CREATE TABLE mlgov.model_version (
    model_version_id        uuid        NOT NULL DEFAULT uuidv7(),
    model_id                uuid        NOT NULL,
    major                   integer     NOT NULL,
    minor                   integer     NOT NULL DEFAULT 0,
    patch                   integer     NOT NULL DEFAULT 0,
    version_label           text,
    created_at              timestamptz NOT NULL DEFAULT now(),
    created_by_actor_id     uuid        NOT NULL,
    created_role_code       text        NOT NULL,
    CONSTRAINT pk_model_version PRIMARY KEY (model_version_id),
    CONSTRAINT fk_model_version_model FOREIGN KEY (model_id)
        REFERENCES mlgov.model (model_id) ON DELETE RESTRICT,
    CONSTRAINT fk_model_version_created_by FOREIGN KEY (created_by_actor_id)
        REFERENCES mlgov.actor (actor_id) ON DELETE RESTRICT,
    CONSTRAINT fk_model_version_created_role FOREIGN KEY (created_role_code)
        REFERENCES mlgov.role (code) ON DELETE RESTRICT,
    CONSTRAINT uq_model_version_semver UNIQUE (model_id, major, minor, patch),
    CONSTRAINT ck_model_version_major_nonneg CHECK (major >= 0),
    CONSTRAINT ck_model_version_minor_nonneg CHECK (minor >= 0),
    CONSTRAINT ck_model_version_patch_nonneg CHECK (patch >= 0)
);
COMMENT ON TABLE mlgov.model_version IS
'An immutable version of a model. Every other table in this schema — lifecycle_event, champion_assignment, model_card, approval_request, hitl_override (via prediction_event) — points at a model_version, never at the bare model. External facts this version relates to (a SageMaker model package, a Feast Feature Service, an MLflow model version, or any future external system) are held directly as rows in model_version_external_reference, keyed by external_system_code — never as named columns here, so adding a new external system never requires a schema change to this table.';
COMMENT ON COLUMN mlgov.model_version.major IS
'Major version number. Uniqueness and ordering are based on (major, minor, patch), not on version_label, so a version can never be ambiguous or miskeyed the way a free-text label could be.';
COMMENT ON COLUMN mlgov.model_version.minor IS
'Minor version number. Defaults to 0 for a model_version created without an explicit minor bump.';
COMMENT ON COLUMN mlgov.model_version.patch IS
'Patch version number. Defaults to 0 for a model_version created without an explicit patch bump.';
COMMENT ON COLUMN mlgov.model_version.version_label IS
'Optional human-facing display string (e.g. a release codename). Not authoritative and not part of any uniqueness constraint — (model_id, major, minor, patch) is what identifies a version.';

-- Now that model_version exists, add model_version_external_reference's
-- forward reference to it.
ALTER TABLE mlgov.model_version_external_reference
    ADD CONSTRAINT fk_model_version_external_reference_version FOREIGN KEY (model_version_id)
        REFERENCES mlgov.model_version (model_version_id) ON DELETE RESTRICT;


CREATE TABLE mlgov.lifecycle_event (
    lifecycle_event_id  uuid        NOT NULL DEFAULT uuidv7(),
    model_version_id    uuid        NOT NULL,
    from_state_code      text,
    to_state_code        text        NOT NULL,
    approval_request_id  uuid,
    rationale            text        NOT NULL,
    actor_id             uuid        NOT NULL,
    acting_role_code     text        NOT NULL,
    created_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_lifecycle_event PRIMARY KEY (lifecycle_event_id),
    CONSTRAINT fk_lifecycle_event_version FOREIGN KEY (model_version_id)
        REFERENCES mlgov.model_version (model_version_id) ON DELETE RESTRICT,
    CONSTRAINT fk_lifecycle_event_from FOREIGN KEY (from_state_code)
        REFERENCES mlgov.lifecycle_state (code) ON DELETE RESTRICT,
    CONSTRAINT fk_lifecycle_event_to FOREIGN KEY (to_state_code)
        REFERENCES mlgov.lifecycle_state (code) ON DELETE RESTRICT,
    -- approval_request FK is added after approval_request is created, below.
    CONSTRAINT fk_lifecycle_event_actor FOREIGN KEY (actor_id)
        REFERENCES mlgov.actor (actor_id) ON DELETE RESTRICT,
    CONSTRAINT fk_lifecycle_event_role FOREIGN KEY (acting_role_code)
        REFERENCES mlgov.role (code) ON DELETE RESTRICT,
    CONSTRAINT ck_lifecycle_event_no_self_loop CHECK (from_state_code IS NULL OR from_state_code <> to_state_code)
);
COMMENT ON TABLE mlgov.lifecycle_event IS
'Append-only state machine for a model_version. There is no mutable "current state" column anywhere — current state is the view model_lifecycle_current, resolved from the latest row here. A transition into champion is expected to carry an approval_request_id (the gate); this is not enforced by a CHECK constraint at this scale, left as an application-level rule for now.';
COMMENT ON COLUMN mlgov.lifecycle_event.from_state_code IS
'State before the transition; null only on the version''s first event (entry into draft).';
COMMENT ON COLUMN mlgov.lifecycle_event.approval_request_id IS
'The gating approval for this transition, when one was required (e.g. promotion to champion). Null for ungated moves.';
COMMENT ON COLUMN mlgov.lifecycle_event.rationale IS
'Why the transition was made — a required audit fact, not optional.';


CREATE TABLE mlgov.champion_assignment (
    champion_assignment_id uuid        NOT NULL DEFAULT uuidv7(),
    model_version_id       uuid        NOT NULL,
    is_revocation           boolean     NOT NULL DEFAULT false,
    lifecycle_event_id      uuid,
    reason                  text,
    actor_id                uuid        NOT NULL,
