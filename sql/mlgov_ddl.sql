    created_at              timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_champion_assignment PRIMARY KEY (champion_assignment_id),
    CONSTRAINT fk_champion_assignment_version FOREIGN KEY (model_version_id)
        REFERENCES mlgov.model_version (model_version_id) ON DELETE RESTRICT,
    CONSTRAINT fk_champion_assignment_event FOREIGN KEY (lifecycle_event_id)
        REFERENCES mlgov.lifecycle_event (lifecycle_event_id) ON DELETE RESTRICT,
    CONSTRAINT fk_champion_assignment_actor FOREIGN KEY (actor_id)
        REFERENCES mlgov.actor (actor_id) ON DELETE RESTRICT,
    CONSTRAINT fk_champion_assignment_role FOREIGN KEY (acting_role_code)
        REFERENCES mlgov.role (code) ON DELETE RESTRICT
);
CREATE INDEX ix_champion_assignment_version_time
    ON mlgov.champion_assignment (model_version_id, created_at DESC);
COMMENT ON TABLE mlgov.champion_assignment IS
'Append-only champion pointer: assign and revoke events. The current champion for a model is the latest non-revoked assignment among its versions, resolved by the view model_champion_current — there is no mutable "is_champion" column. Keeps a full, auditable promotion history rather than overwriting a single flag.';
COMMENT ON COLUMN mlgov.champion_assignment.is_revocation IS
'True if this event demotes the version rather than promoting it to champion.';


CREATE VIEW mlgov.model_lifecycle_current AS
SELECT DISTINCT ON (model_version_id)
    model_version_id,
    to_state_code AS current_state_code,
    created_at    AS since
FROM mlgov.lifecycle_event
ORDER BY model_version_id, created_at DESC;
COMMENT ON VIEW mlgov.model_lifecycle_current IS
'Current lifecycle state of each model_version: the to_state_code of its most recent lifecycle_event.';


CREATE VIEW mlgov.model_champion_current AS
SELECT DISTINCT ON (model_version_id)
    model_version_id,
    is_revocation,
    created_at AS since
FROM mlgov.champion_assignment
ORDER BY model_version_id, created_at DESC;
COMMENT ON VIEW mlgov.model_champion_current IS
'Per model_version, whether its latest champion_assignment event is a live assignment (is_revocation = false) or a revocation. A model''s actual current champion is the model_version, among its own versions, whose latest row here has is_revocation = false — query this view joined back to model_version.model_id, not this view alone.';


